export const xpRules = {
  /** XP to go from level L to L + 1: round(base × L^exponent). */
  base: 75,
  exponent: 1.65,
  /** No XP past this level; the top of the tier 5 band. */
  maxLevel: 15,
  /** Share of XP from dungeons 0, 1, and 2 or more tiers below the highest unlocked tier. */
  lowerTierShare: [1, 0.5, 0.25],
  /** Levels past the band's top still earned at full share; the soft cap starts above them. */
  aboveBandMargin: 1,
  /** A hero at or above the top of the player's tier band plus `aboveBandMargin` gets this share of XP. */
  aboveBandShare: 0.25,
};

/** XP needed to go from `level` to `level + 1`. */
export const xpToNextLevel = (level: number, rules: typeof xpRules = xpRules) => Math.round(rules.base * level ** rules.exponent);

